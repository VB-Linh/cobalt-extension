// src/background/clients/sessionClient.js
import { normalizeCobaltUrl, validateCobaltUrl } from '../../shared/utils/urlHelper.js';
import { classifyCobaltError } from '../handlers/cobaltResponseHandler.js';

export const SESSION_REQUEST_TIMEOUT_MS = 15000;

/**
 * Validates the raw response structure from Cobalt POST /session.
 * Strict check ensuring token is a non-empty string and exp is a positive number.
 * 
 * @param {any} data
 * @returns {{ valid: boolean, error?: string }}
 */
export function validateSessionResponse(data) {
  if (!data || typeof data !== 'object') {
    return { valid: false, error: 'MALFORMED_SESSION_DATA' };
  }

  if (typeof data.token !== 'string' || !data.token.trim()) {
    return { valid: false, error: 'INVALID_SESSION_TOKEN' };
  }

  if (typeof data.exp !== 'number' || Number.isNaN(data.exp) || data.exp <= 0) {
    return { valid: false, error: 'INVALID_SESSION_EXPIRY' };
  }

  return { valid: true };
}

/**
 * Requests a JWT session token from Cobalt v11.7.1 POST /session
 * using an official Cloudflare Turnstile challenge response token.
 * 
 * @param {string} instanceUrl - Base URL of the Cobalt instance
 * @param {string} turnstileResponse - Token generated by official Turnstile widget
 * @param {object} [options]
 * @param {number} [options.timeout=15000] - Request timeout in ms
 * @param {AbortSignal} [options.signal] - Optional external cancellation signal
 * @returns {Promise<{ success: boolean, token?: string, exp?: number, error?: string, code?: string, message?: string }>}
 */
export async function requestSession(instanceUrl, turnstileResponse, options = {}) {
  if (!instanceUrl || typeof instanceUrl !== 'string' || !instanceUrl.trim()) {
    return {
      success: false,
      error: 'UNCONFIGURED',
      code: 'UNCONFIGURED',
      message: 'Chưa cài đặt Cobalt URL. Vui lòng thiết lập trong cài đặt.',
    };
  }

  const urlValidation = validateCobaltUrl(instanceUrl);
  if (!urlValidation.valid) {
    return {
      success: false,
      error: 'INVALID_URL',
      code: 'INVALID_URL',
      message: 'URL máy chủ Cobalt không hợp lệ.',
    };
  }

  if (!turnstileResponse || typeof turnstileResponse !== 'string' || !turnstileResponse.trim()) {
    return {
      success: false,
      error: 'TURNSTILE_RESPONSE_MISSING',
      code: 'TURNSTILE_RESPONSE_MISSING',
      message: 'Thiếu mã xác thực Turnstile. Vui lòng hoàn thành xác thực.',
    };
  }

  const normalizedBase = normalizeCobaltUrl(instanceUrl);
  const endpoint = `${normalizedBase}/session`;
  const timeoutMs = typeof options.timeout === 'number' ? options.timeout : SESSION_REQUEST_TIMEOUT_MS;

  const controller = new AbortController();
  let didTimeout = false;
  const timer = setTimeout(() => {
    didTimeout = true;
    controller.abort();
  }, timeoutMs);

  if (options.signal) {
    if (options.signal.aborted) {
      controller.abort();
    } else {
      options.signal.addEventListener('abort', () => controller.abort(), { once: true });
    }
  }

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: {
        'Accept': 'application/json',
        'cf-turnstile-response': turnstileResponse.trim(),
      },
      signal: controller.signal,
    });

    clearTimeout(timer);

    let data;
    try {
      data = await res.json();
    } catch {
      return {
        success: false,
        error: 'MALFORMED_RESPONSE',
        code: 'MALFORMED_RESPONSE',
        message: 'Máy chủ phản hồi dữ liệu không hợp lệ.',
      };
    }

    if (!res.ok || data.status === 'error') {
      const classified = classifyCobaltError(data);
      return {
        success: false,
        error: classified.code || data.error?.code || 'AUTH_SESSION_REJECTED',
        code: classified.code || data.error?.code || 'AUTH_SESSION_REJECTED',
        rawCode: data.error?.code || classified.rawCode,
        message: classified.message || 'Xác thực Turnstile không thành công hoặc bị máy chủ từ chối.',
        httpStatus: res.status,
      };
    }

    const structureValidation = validateSessionResponse(data);
    if (!structureValidation.valid) {
      return {
        success: false,
        error: structureValidation.error,
        code: structureValidation.error,
        message: 'Phản hồi phiên xác thực từ máy chủ không đúng định dạng chuẩn.',
      };
    }

    return {
      success: true,
      token: data.token,
      exp: data.exp,
    };
  } catch (err) {
    clearTimeout(timer);

    if (didTimeout) {
      return {
        success: false,
        error: 'TIMEOUT',
        code: 'TIMEOUT',
        message: 'Hết thời gian chờ phản hồi xác thực từ máy chủ Cobalt.',
      };
    }

    if (options.signal?.aborted || err.name === 'AbortError') {
      return {
        success: false,
        error: 'ABORTED',
        code: 'ABORTED',
        message: 'Yêu cầu xác thực đã bị hủy.',
      };
    }

    return {
      success: false,
      error: 'UNREACHABLE',
      code: 'UNREACHABLE',
      message: 'Không thể kết nối tới máy chủ để xác thực phiên: ' + err.message,
    };
  }
}
